"""Prompt 模板集中管理。

## 为什么 Prompt 要单独一个文件

1. **可版本化**：Prompt 是 RAG 效果的第一影响因子，必须能 diff、能回归测试；
   散落在代码里的 f-string 改了都不知道改了什么。
2. **可 A/B**：`PROMPT_VERSION` 可以直接写进日志，出了问题能定位到是模板变了。
3. **中文 Prompt 有专门讲究**（见下方注释），不是把英文模板翻译一遍就行。

## 本项目 Prompt 设计的四条硬规则

| 规则 | 目的 | 违反后果 |
|---|---|---|
| 只允许依据参考资料回答 | 抑制幻觉 | 模型用预训练知识编答案，引用对不上 |
| 每个事实性陈述必须带 `[n]` | 可溯源 | 无法验证，项目卖点全失 |
| 资料不足必须明说「无法回答」 | 诚实的拒答 | 强行编一个看似合理的答案 |
| 引用编号必须与给定编号一致 | 绑定正确 | 引用张冠李戴 |

此外还有两条中文特有的经验：

- **必须用「参考资料」而不是「上下文」**：中文模型对「上下文」的理解偏向
  对话历史，会把用户前几轮说的话也当成可引用材料，导致引用编号错位。
- **输出语言要显式约束**：混排场景（中文问、英文文档）下模型容易跟随文档
  语言作答，必须写明「用中文回答」。
"""

from __future__ import annotations

from langchain_core.documents import Document

PROMPT_VERSION = "v1.3"

# ============================================================
#  System Prompt
# ============================================================
SYSTEM_PROMPT = """你是一名严谨的企业知识库问答助手。你的回答必须**完全基于**用户提供的参考资料。

【回答要求】
1. **只用参考资料回答**：不允许使用你自己的先验知识补充事实。如果资料里没有，就不要说。
2. **强制引用**：每一个事实性陈述（数字、日期、名称、规定、流程步骤）后面必须紧跟引用标记，
   格式为方括号加编号，例如：员工每年享有 5 天年假[1]。多个来源写在一起：试用期为 3 个月[2][3]。
3. **编号必须来自参考资料**：只能使用资料中已给出的 [1]、[2] 等编号，不得自己新造编号，
   也不能改变编号与资料的对应关系。
4. **资料不足就明说**：如果参考资料无法回答问题，直接回答：
   「根据现有资料无法回答该问题。」然后一句话说明缺少什么信息。**不要猜测、不要编造**。
5. **语言**：无论参考资料是什么语言，都用**中文**回答。
6. **结构**：先用 1~3 句话给出结论，再补充必要细节。不要输出「根据参考资料」「上述资料显示」这类
   元话语开头，直接说结论。
7. **不要复述问题**，不要写「您好，很高兴为您解答」这类客套话。

【输出格式】
- 纯文本即可，允许使用 `-` 列出要点。
- 不要在末尾单独列出「参考来源」清单，引用标记已经在正文里了。
"""

# ============================================================
#  用户消息模板
# ============================================================
USER_TEMPLATE = """【参考资料】
{context}
===== 参考资料结束 =====

【历史对话】
{history}

【本次问题】
{question}
===== 问题结束 =====

请基于上述参考资料回答「本次问题」。记得在每个事实后标注 [编号]。"""

# 单条资料块的模板：`[编号] 来源 | 第N页 \n 正文`
CONTEXT_BLOCK_TEMPLATE = "[{index}] 来源：{source}{page_part}\n{content}"

# 没有历史时的占位（保持 prompt 结构稳定，便于模型复用缓存）
NO_HISTORY_PLACEHOLDER = "（无历史对话，这是本轮对话的第一个问题）"

# 资料为空时的占位
NO_CONTEXT_PLACEHOLDER = "（没有检索到任何相关资料）"

# ============================================================
#  离线抽取模式的提示（前端展示用）
# ============================================================
OFFLINE_NOTICE = (
    "⚠️ 当前为**离线抽取模式**：未配置大模型 API Key，"
    "以下答案直接从检索到的原文中抽取拼接，**未经语言模型润色或推理**。"
    "配置 LLM_API_KEY 后即可获得真正的生成式回答。"
)

# ============================================================
#  拒答话术（检索为空时直接返回，不浪费一次 LLM 调用）
# ============================================================
NO_RESULT_ANSWER = (
    "根据现有知识库无法回答该问题：没有检索到与该问题相关的文档片段。\n\n"
    "可能的原因：\n"
    "1. 知识库里还没有入库相关文档 —— 请先在左侧上传文件并点击「入库」；\n"
    "2. 问题用词与文档差异过大 —— 换一种更贴近原文的说法，或换个关键词再问；\n"
    "3. 文档已入库但切分/检索参数不合适 —— 可尝试调大「检索片段数」。"
)

# ============================================================
#  拒答的**结构化识别**
#
#  为什么需要：如果只把拒答当成一段「特殊文案」，那么上层（前端 / 评测脚本 /
#  调用方）就只能靠**字符串匹配**去猜「这算不算拒答」——文案改一个字判断就失灵，
#  而且「拒答准确率」这个指标本身也就不可信了。
#
#  正确做法：在链路里判定一次，作为 `refused` / `refusal_reason` 字段一路传出去。
#  这里只放**Prompt 契约里明确约定过**的固定话术；
#  绝不能放「没有」「不知道」这类会误伤正常答案的通用词。
# ============================================================
REFUSAL_MARKERS: tuple[str, ...] = (
    "根据现有知识库无法回答",  # 离线模式：检索为空或相关度闸门拒绝
    "根据现有资料无法回答",    # 在线模式：Prompt 里约定的拒答话术
    "无法根据现有资料",        # 同一语义的另一种自然表达
)

# 拒答原因（写入 response.refusal_reason，便于排查「到底为什么答不上来」）
REFUSAL_NO_RETRIEVAL = "no_retrieval"    # 检索阶段没拿到任何片段
REFUSAL_MODEL = "model_refused"          # 模型/离线闸门判定资料不足而拒答
REFUSAL_EMPTY_OUTPUT = "empty_output"    # 模型返回空字符串（异常，不应静默通过）


def is_refusal_text(text: str | None) -> bool:
    """判断一段答案文本是否属于「拒答」。

    只看**开头一小段**：约定好的拒答话术永远出现在最前面，这样即使答案后面
    跟着解释性文字也能稳定识别；同时避免在正文里偶然命中特征串造成误判。

    Args:
        text: 待判定的答案文本。

    Returns:
        True 表示这是拒答话术（含空文本，因为空产出等于「答不上来」）。
    """
    if not text or not text.strip():
        return True
    head = text.strip()[:80]
    return any(marker in head for marker in REFUSAL_MARKERS)



def format_context(documents: list[Document]) -> tuple[str, list[tuple[int, Document]]]:
    """把检索到的 Document 列表格式化成带编号的参考资料文本。

    编号从 1 开始，**与最终引用里展示的 index 严格对应** ——
    这是「引用绑定准确率」的基础。编号错位是 RAG 系统最常见的 bug。

    Args:
        documents: 检索结果（已按相关性降序）。

    Returns:
        `(context_text, [(index, document)])`；
        输入为空时返回 `(NO_CONTEXT_PLACEHOLDER, [])`。

    Raises:
        无。
    """
    if not documents:
        return NO_CONTEXT_PLACEHOLDER, []

    blocks: list[str] = []
    indexed: list[tuple[int, Document]] = []

    for i, doc in enumerate(documents, start=1):
        meta = doc.metadata
        source = str(meta.get("source", "未知来源"))
        page = meta.get("page")
        page_part = f" | 第 {page} 页" if page is not None else ""

        blocks.append(
            CONTEXT_BLOCK_TEMPLATE.format(
                index=i,
                source=source,
                page_part=page_part,
                content=doc.page_content.strip(),
            )
        )
        indexed.append((i, doc))

    return "\n\n".join(blocks), indexed


def format_history(history: list[tuple[str, str]], max_turns: int = 6) -> str:
    """把多轮对话历史格式化成文本。

    为什么只保留最近 N 轮：
    - 上下文窗口有限，历史越长越挤占参考资料的空间（而参考资料才是答案依据）；
    - 太久远的对话和当前问题通常无关，反而会引入噪声、带偏检索。

    Args:
        history: `[(用户问题, 助手回答)]` 列表，按时间正序。
        max_turns: 最多保留多少轮。

    Returns:
        格式化后的历史文本；无历史时返回占位符。
    """
    if not history:
        return NO_HISTORY_PLACEHOLDER

    recent = history[-max_turns:]
    lines: list[str] = []
    for q, a in recent:
        # 助手回答可能很长（含引用），历史里截断到 200 字，只保留语义
        a_short = a if len(a) <= 200 else a[:200] + "…"
        lines.append(f"用户：{q}\n助手：{a_short}")

    return "\n".join(lines)


def build_query_rewrite_prompt(question: str, history: list[tuple[str, str]]) -> str:
    """生成「查询改写」的 Prompt（多轮对话里把指代词还原成实体）。

    解决的问题：
        第 1 轮：「公司的年假有多少天？」→ 检索「年假」
        第 2 轮：「那病假呢？」→ 直接拿「那病假呢？」去检索，
        「那」「呢」是噪声，检索质量暴跌。

    做法：让 LLM 把「那病假呢？」结合历史改写成「公司的病假有多少天？」，
    再用改写后的查询去做检索。这一步能显著提升多轮场景的召回率。

    注意：这个功能**只在在线模式下启用**（离线抽取没法做改写），
    所以它是一个「可选增强」，不是主链路的必经环节。

    Args:
        question: 本轮原始问题。
        history: 历史对话。

    Returns:
        完整的改写指令 Prompt。
    """
    return f"""请把用户的最新问题改写成一个**可以独立检索的完整问题**。

要求：
- 把代词（它/他/那/这个）替换成历史对话里的具体实体。
- 补全省略的主语和宾语。
- 保持原意，不要回答问题，不要添加历史里没有的信息。
- **只输出改写后的问题本身**，不要任何解释、引号或前缀。

【历史对话】
{format_history(history, max_turns=4)}

【最新问题】
{question}

【改写结果】"""
